# Generate the bounded GUI v1 C declarations and reject stale checked-in output.
from pathlib import Path
import sys


STRUCTS = {
    "version": (32, 4, "uint32_t abi_version, struct_size, max_width, max_height;\n    uint32_t max_text_bytes, event_size, capabilities, reserved;"),
    "window_desc": (32, 4, "uint32_t abi_version, struct_size;\n    int32_t x, y;\n    uint32_t width, height, flags, reserved;"),
    "rect": (16, 4, "int32_t x, y;\n    uint32_t width, height;"),
    "event": (48, 4, "uint32_t kind, key, codepoint, modifiers;\n    int32_t x, y;\n    uint32_t buttons, changed, width, height, state, reserved;"),
    "layout": (28, 4, "struct anova_gui_rect bounds;\n    uint32_t cursor, gap, row_height;"),
}

FUNCTIONS = [
    "query_version(uint32_t requested, struct anova_gui_version *output)",
    "window_create(const struct anova_gui_window_desc *description, uint64_t *output)",
    "window_destroy(uint64_t window)",
    "window_show(uint64_t window, uint32_t visible)",
    "window_clear(uint64_t window, uint32_t rgb)",
    "draw_rect(uint64_t window, struct anova_gui_rect rectangle, uint32_t rgb)",
    "draw_text(uint64_t window, int32_t x, int32_t y, const uint8_t *text, uint32_t length, uint32_t rgb)",
    "draw_button(uint64_t window, struct anova_gui_rect rectangle, const uint8_t *text, uint32_t length, const struct anova_gui_event *event, uint32_t *activated)",
    "draw_textfield(uint64_t window, struct anova_gui_rect rectangle, uint8_t *text, uint32_t capacity, uint32_t *length, const struct anova_gui_event *event)",
    "window_present(uint64_t window)",
    "poll_event(uint64_t window, struct anova_gui_event *output)",
    "layout_next(struct anova_gui_layout *layout, struct anova_gui_rect *output)",
    "clipboard_set(const uint8_t *text, uint32_t length)",
    "clipboard_get(uint8_t *output, uint32_t capacity, uint32_t *written)",
]


def generate():
    parts = ["""/* SPDX-License-Identifier: Apache-2.0 */
/* Generated by sdk/gui/generate.py: fixed-width GUI v1 calls into the Rust user runtime. */
#ifndef ANOVA_GUI_V1_H
#define ANOVA_GUI_V1_H
#include <stdint.h>
#include <stddef.h>

#define ANOVA_GUI_ABI_VERSION UINT32_C(0x00010000)
#define ANOVA_GUI_VISIBLE UINT32_C(1)
#define ANOVA_GUI_CAP_RASTER UINT32_C(1)
#define ANOVA_GUI_CAP_WIDGETS UINT32_C(2)
#define ANOVA_GUI_CAP_CLIPBOARD UINT32_C(4)
#define ANOVA_GUI_EVENT_RESET UINT32_C(1)
#define ANOVA_GUI_EVENT_KEY UINT32_C(2)
#define ANOVA_GUI_EVENT_POINTER UINT32_C(3)
#define ANOVA_GUI_KEY_PRESS UINT32_C(1)
#define ANOVA_GUI_KEY_RELEASE UINT32_C(2)
#define ANOVA_GUI_KEY_REPEAT UINT32_C(3)
#define ANOVA_GUI_OK 0
#define ANOVA_GUI_INVALID (-1)
#define ANOVA_GUI_VERSION (-2)
#define ANOVA_GUI_STALE (-3)
#define ANOVA_GUI_LIMIT (-4)
#define ANOVA_GUI_UTF8 (-5)
#define ANOVA_GUI_WOULD_BLOCK (-6)
#define ANOVA_GUI_DISCONNECTED (-7)
#define ANOVA_GUI_BUSY (-8)
#define ANOVA_GUI_TRANSPORT (-9)
#define ANOVA_GUI_BUFFER (-10)

#ifdef __cplusplus
#define ANOVA_GUI_ASSERT static_assert
#define ANOVA_GUI_ALIGNOF alignof
extern "C" {
#else
#define ANOVA_GUI_ASSERT _Static_assert
#define ANOVA_GUI_ALIGNOF _Alignof
#endif

/* UI-thread only; no callbacks, re-entry, exceptions, allocator or borrowed outputs.
 * Every text input is UTF-8 and borrowed only until return; lengths count bytes.
 * Output pointers belong to the caller. Handles are opaque, process-local and
 * invalid after destroy/disconnect. Zero is never a live handle. Errors are
 * stable negative values; unknown values must remain observable to callers.
 * Events preserve server ordering; RESET clears held input after focus/loss.
 * Pointer coordinates are window-local. Poll returns WOULD_BLOCK if empty.
 * Colors are 0x00RRGGBB. Clipboard is bounded, process-local and nonpersistent.
 * See sdk/gui/README.md for precise bounds, lifetime and overflow semantics. */
"""]
    for name, (size, align, fields) in STRUCTS.items():
        tag = "anova_gui_" + name
        parts.append(f"struct {tag} {{\n    {fields}\n}};\n")
        parts.append(f'ANOVA_GUI_ASSERT(sizeof(struct {tag}) == {size}, "GUI {name} size");\n')
        parts.append(f'ANOVA_GUI_ASSERT(ANOVA_GUI_ALIGNOF(struct {tag}) == {align}, "GUI {name} alignment");\n')
    parts.append('\nANOVA_GUI_ASSERT(offsetof(struct anova_gui_event, x) == 16, "GUI event x offset");\n')
    parts.append('ANOVA_GUI_ASSERT(offsetof(struct anova_gui_event, state) == 40, "GUI event state offset");\n')
    parts.append('ANOVA_GUI_ASSERT(offsetof(struct anova_gui_window_desc, width) == 16, "GUI width offset");\n')
    parts.append('ANOVA_GUI_ASSERT(offsetof(struct anova_gui_layout, cursor) == 16, "GUI cursor offset");\n\n')
    parts.extend("int32_t anova_gui_" + declaration + ";\n" for declaration in FUNCTIONS)
    parts.append("\n#ifdef __cplusplus\n}\n#endif\n#endif\n")
    return "".join(parts)


if __name__ == "__main__":
    target = Path(__file__).resolve().parent / "include/anova_gui.h"
    expected = generate()
    if sys.argv[1:] == ["--check"]:
        if not target.is_file() or target.read_text() != expected:
            raise SystemExit("GUI header is stale; run python3 sdk/gui/generate.py")
    elif sys.argv[1:]:
        raise SystemExit("Usage: generate.py [--check]")
    else:
        target.write_text(expected)
